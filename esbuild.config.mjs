// Bundles src/ into main.js, the single file Obsidian loads.
//   npm run build  -> one-off build
//   npm run dev    -> rebuild on every change in src/

import esbuild from "esbuild";

const watch = process.argv.includes("--watch");

const pluginBuild = {
  entryPoints: ["src/main.js"],
  outfile: "main.js",
  bundle: true,
  platform: "node", // keeps Node built-ins (fs, path, child_process) external
  format: "cjs",
  target: "es2020",
  // Provided by Obsidian/Electron at runtime. xterm is loaded from node_modules at runtime too.
  external: ["obsidian", "electron", "@xterm/*", "node-pty"],
  logLevel: "info",
  banner: { js: "/* Generated by esbuild from src/ — edit the files in src/, not this one. */" },
};

const mcpBuild = {
  entryPoints: ["src/mcp-server.js"],
  outfile: "mcp-server.js",
  bundle: true,
  platform: "node",
  format: "cjs",
  target: "node18",
  logLevel: "info",
  banner: { js: "#!/usr/bin/env node\n/* Generated by esbuild from src/mcp-server.js. */" },
};

if (watch) {
  const pluginContext = await esbuild.context(pluginBuild);
  const mcpContext = await esbuild.context(mcpBuild);
  await Promise.all([pluginContext.watch(), mcpContext.watch()]);
} else {
  const ctx = await esbuild.context(pluginBuild);
  await ctx.rebuild();
  await ctx.dispose();
  await esbuild.build(mcpBuild);
}
